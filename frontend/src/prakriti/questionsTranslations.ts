export function getTranslatedQuestion(questionId: number, lang: string): string {
  const normalizedLang = lang.split('-')[0]; // Handle cases like 'en-US' -> 'en'
  const translation = QUESTIONS_TRANSLATIONS[normalizedLang] || QUESTIONS_TRANSLATIONS['en'];
  return translation[questionId]?.question || "";
}

export function getTranslatedOption(questionId: number, optionIndex: number, lang: string): string {
  const normalizedLang = lang.split('-')[0];
  const translation = QUESTIONS_TRANSLATIONS[normalizedLang] || QUESTIONS_TRANSLATIONS['en'];
  return translation[questionId]?.options[optionIndex] || "";
}
